const FONT = "Calibri"
const MONEY = '_(* #,##0_);_(* (#,##0);_(* "-"??_);_(@_)'
const DAYFMT = '[=1]"P";[=0]"A";0.0#'

const pad = (n) => String(n).padStart(2, "0")
export const colL = (n) => {
  let s = ""
  while (n > 0) {
    const m = (n - 1) % 26
    s = String.fromCharCode(65 + m) + s
    n = Math.floor((n - 1) / 26)
  }
  return s
}
const fmtDate = (iso) => {
  if (!iso) return ""
  const [y, m, d] = String(iso).slice(0, 10).split("-").map(Number)
  return `${pad(d)}.${pad(m)}.${y}`
}
const isoDate = (iso) => {
  if (!iso) return null
  const [y, m, d] = String(iso).slice(0, 10).split("-").map(Number)
  return new Date(Date.UTC(y, m - 1, d))
}

// ---- cell helpers ----
const thin = { style: "thin", color: { argb: C.border } }
const box = { top: thin, left: thin, bottom: thin, right: thin }
const fill = (argb) => ({ type: "pattern", pattern: "solid", fgColor: { argb } })

function cellStyle(cell, o = {}) {
  cell.font = {
    name: FONT,
    size: o.size || 10,
    bold: !!o.bold,
    italic: !!o.italic,
    color: { argb: o.color || C.ink },
  }
  if (o.fill) cell.fill = fill(o.fill)
  if (o.border !== false) cell.border = o.border || box
  cell.alignment = {
    horizontal: o.h || undefined,
    vertical: o.v || "middle",
    wrapText: !!o.wrap,
  }
  if (o.fmt) cell.numFmt = o.fmt
}
const F = (formula, result) => ({ formula, result })

// Company letterhead + title, merged across `width` columns. Returns next row.
function letterhead(ws, width, company, title, subtitle) {
  const last = colL(width)
  const line = (r, text, o) => {
    ws.mergeCells(`A${r}:${last}${r}`)
    const c = ws.getCell(`A${r}`)
    c.value = text
    cellStyle(c, { ...o, h: "center", border: false })
  }
  line(1, company.name, { size: 16, bold: true, color: C.navyDark })
  ws.getRow(1).height = 24
  line(2, [company.address1, company.address2].filter(Boolean).join(" "), {
    size: 10,
    color: C.slate,
  })
  line(3, title, { size: 13, bold: true })
  ws.getRow(3).height = 20
  if (subtitle) line(4, subtitle, { size: 10, color: C.slate })
  return subtitle ? 6 : 5
}

// Signature line under the table: labels spread over the printed width.
function signatures(ws, row, width, labels) {
  const span = Math.max(2, Math.floor(width / labels.length))
  labels.forEach((label, i) => {
    const from = 1 + i * span + (i === labels.length - 1 ? width - span * labels.length : 0)
    const to = Math.min(width, from + Math.max(1, Math.floor(span * 0.75)))
    ws.mergeCells(`${colL(from)}${row}:${colL(to)}${row}`)
    const c = ws.getCell(`${colL(from)}${row}`)
    c.value = label
    cellStyle(c, {
      bold: true,
      h: "center",
      border: { top: { style: "thin", color: { argb: C.ink } } },
    })
  })
  ws.getRow(row).height = 20
}

function printSetup(ws, lastCol, lastRow, titleRows) {
  ws.pageSetup = {
    paperSize: 9, // A4
    orientation: "landscape",
    fitToPage: true,
    fitToWidth: 1,
    fitToHeight: 0,
    horizontalCentered: true,
    margins: { left: 0.25, right: 0.25, top: 0.4, bottom: 0.4, header: 0.2, footer: 0.2 },
    printArea: `A1:${colL(lastCol)}${lastRow}`,
    printTitlesRow: titleRows,
  }
  ws.headerFooter = { oddFooter: "&L&8&K475569Generated by GreenTouch&R&8&K475569Page &P of &N" }
}

// Grouped header cell spanning [from..to] on `row`.
function groupHead(ws, row, from, to, text, o = {}) {
  if (to > from) ws.mergeCells(`${colL(from)}${row}:${colL(to)}${row}`)
  const c = ws.getCell(`${colL(from)}${row}`)
  c.value = text
  cellStyle(c, { bold: true, h: "center", fill: o.fill || C.group, color: C.navyDark, size: 9 })
  for (let k = from + 1; k <= to; k++) ws.getCell(`${colL(k)}${row}`).border = box
}
function colHead(ws, row, col, text, o = {}) {
  const c = ws.getCell(`${colL(col)}${row}`)
  c.value = text
  cellStyle(c, {
    bold: true, h: "center", wrap: true,
    fill: o.fill || C.navy, color: o.color || C.white, size: o.size || 9,
    fmt: o.fmt,
  })
  return c
}

