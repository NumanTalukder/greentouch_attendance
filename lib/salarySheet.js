// Sheet: Bonus (festival bonus — only when provided)
// ======================================================================
function sheetBonus(wb, input) {
  const b = input.bonus
  const ws = wb.addWorksheet("Bonus", { properties: { tabColor: { argb: "FF15803D" } } })
  const heads = [
    ["S.L", 5], ["Name", 26], ["Designation", 26], ["Existing Salary", 13],
    ["Gross Bonus", 13], ["Already Paid", 13], ["Net Bonus", 13], ["Signature", 22],
  ]
  const W = heads.length
  heads.forEach(([, w], i) => (ws.getColumn(i + 1).width = w))
  letterhead(ws, W, input.company, b.title || "Festival Bonus",
    `Date: ${fmtDate(b.date)}  ·  Bonus = ${Math.round((b.rate ?? 0.5) * 100)}% of existing salary`)
  const RATE = "D6"
  ws.getCell("C6").value = "Rate"
  cellStyle(ws.getCell("C6"), { bold: true, h: "right", fill: C.group, color: C.navyDark })
  ws.getCell(RATE).value = b.rate ?? 0.5
  cellStyle(ws.getCell(RATE), { fmt: "0%", bold: true, h: "center" })
  const H = 8
  heads.forEach(([t], i) => colHead(ws, H, i + 1, t))
  ws.getRow(H).height = 30
  let r = H + 1
  const first = r
  const rows = (b.rows || []).map((x) => {
    const gross = (Number(x.salary) || 0) * (b.rate ?? 0.5)
    const paid = Number(x.paid) || 0
    return { ...x, gross, paid, net: gross - paid }
  })
  rows.forEach((x, i) => {
    const zebra = i % 2 ? C.zebra : undefined
    const set = (k, v, o = {}) => {
      const c = ws.getCell(`${colL(k)}${r}`)
      c.value = v
      cellStyle(c, { fill: zebra, ...o })
    }
    ws.getRow(r).height = 20
    set(1, i + 1, { h: "center" })
    set(2, x.name, { bold: true })
    set(3, x.designation, { color: C.slate })
    set(4, Number(x.salary) || 0, { fmt: MONEY })
    set(5, F(`D${r}*$D$6`, x.gross), { fmt: MONEY })
    set(6, x.paid, { fmt: MONEY })
    set(7, F(`E${r}-F${r}`, x.net), { fmt: MONEY, bold: true, fill: C.net, color: C.navyDark })
    set(8, "", {})
    r++
  })
  totalRow(ws, r, W, 3, [4, 5, 6, 7], first, r - 1,
    { 4: "salary", 5: "gross", 6: "paid", 7: "net" }, rows)
  signatures(ws, r + 4, W, ["Prepared By", "Checked By", "Director", "Managing Director"])
  ws.views = [{ state: "frozen", ySplit: H, showGridLines: false }]
  printSetup(ws, W, r + 4, `${H}:${H}`)
}

