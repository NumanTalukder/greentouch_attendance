export async function buildSalaryWorkbook(input) {
  const mi = monthInfo(input.month)
  const calc = computeSalary(input)
  const wb = new ExcelJS.Workbook()
  wb.creator = "GreenTouch"
  wb.created = new Date()
  wb.calcProperties = { fullCalcOnLoad: true } // Excel recalculates on open
  const rem = sheetRemuneration(wb, input, calc, mi)
  const sw = sheetSalary(wb, input, calc, mi)
  const ot = sheetOvertime(wb, input, calc, mi)
  if (input.bonus && (input.bonus.rows || []).length) sheetBonus(wb, input)
  sheetSummary(wb, input, calc, mi, { rem, sw, ot })
  return { wb, calc }
}

export async function salaryWorkbookBuffer(input) {
  const { wb, calc } = await buildSalaryWorkbook(input)
  const buf = await wb.xlsx.writeBuffer()
  return { buf, calc }
}

