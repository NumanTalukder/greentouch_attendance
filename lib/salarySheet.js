//   Remuneration · Salary & Wages · Overtime · (Bonus) · Payment Summary
// Same sheets/columns/order as the hand-kept sheet, but with live formulas
// (every formula also carries its computed result), no broken refs, frozen
// panes, a collapsible day grid and print-ready A4 landscape pages.
//
// Pure + isomorphic: runs in the browser or Node. No "@/" imports on purpose.
