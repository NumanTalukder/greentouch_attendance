// Sheet: Payment Summary — one page for approval / the bank
// ======================================================================
function sheetSummary(wb, input, calc, mi, refs) {
  const ws = wb.addWorksheet("Payment Summary", { properties: { tabColor: { argb: "FF15803D" } } })
  const widths = [5, 34, 10, 15, 15, 15, 16]
  widths.forEach((w, i) => (ws.getColumn(i + 1).width = w))
  const W = widths.length
  letterhead(ws, W, input.company, `Payment Summary — ${mi.label}`,
    `Prepared: ${fmtDate(input.preparedDate)}`)
  const H = 7
  ;["#", "Payment head", "People", "Gross", "Additions", "Deductions", "Net payable"].forEach((t, i) =>
    colHead(ws, H, i + 1, t))
  ws.getRow(H).height = 26
  const sw = refs.sw
  const t = calc.totals
  const S = (key) => `'Salary & Wages'!${sw.L(key)}${sw.totalR}`
  const R = (c) => `Remuneration!${c}${refs.rem.totalR}`
  const lines = [
    ["Directors' Remuneration", calc.directors.length,
      F(R("M"), t.dirGross), 0, F(R("P"), t.dirDed), F(R("Q"), t.dirNet)],
    ["Staff Salary & Wages", calc.staff.length,
      F(S("gross"), t.staffGross),
      F(`${S("otPay")}+${S("encash")}+${S("holPay")}+${S("bonus")}`, t.otPay + t.encash + t.holidayPay + t.bonus),
      F(S("totalDed"), t.staffDed),
      F(S("net"), t.staffNet)],
  ]
  let r = H + 1
  const first = r
  lines.forEach((ln, i) => {
    const zebra = i % 2 ? C.zebra : undefined
    ws.getRow(r).height = 22
    ;[i + 1, ...ln].forEach((v, j) => {
      const c = ws.getCell(`${colL(j + 1)}${r}`)
      c.value = v
      cellStyle(c, {
        fill: j === 6 ? C.net : zebra,
        fmt: j >= 3 ? MONEY : undefined,
        h: j === 0 || j === 2 ? "center" : undefined,
        bold: j === 1 || j === 6,
        color: j === 6 ? C.navyDark : C.ink,
      })
    })
    r++
  })
  ws.mergeCells(`A${r}:B${r}`)
  const lbl = ws.getCell(`A${r}`)
  lbl.value = "Grand total"
  cellStyle(lbl, { bold: true, h: "right", fill: C.total })
  ws.getCell(`B${r}`).border = box
  const gt = [
    [3, calc.directors.length + calc.staff.length, "0"],
    [4, F(`SUM(D${first}:D${r - 1})`, t.dirGross + t.staffGross), MONEY],
    [5, F(`SUM(E${first}:E${r - 1})`, t.otPay + t.encash + t.holidayPay + t.bonus), MONEY],
    [6, F(`SUM(F${first}:F${r - 1})`, t.dirDed + t.staffDed), MONEY],
    [7, F(`SUM(G${first}:G${r - 1})`, t.dirNet + t.staffNet), MONEY],
  ]
  gt.forEach(([k, v, fmt]) => {
    const c = ws.getCell(`${colL(k)}${r}`)
    c.value = v
    cellStyle(c, { bold: true, fill: C.total, fmt, h: k === 3 ? "center" : undefined, size: 11 })
  })
  for (let k = 1; k <= W; k++)
    ws.getCell(`${colL(k)}${r}`).border = { ...box, top: { style: "double", color: { argb: C.ink } } }
  ws.getRow(r).height = 24

  // breakdown blocks that tie back to the totals above
  const block = (title, rows) => {
    r += 2
    ws.mergeCells(`B${r}:D${r}`)
    const h = ws.getCell(`B${r}`)
    h.value = title
    cellStyle(h, { bold: true, fill: C.group, color: C.navyDark })
    const top = r + 1
    rows.forEach(([label, v]) => {
      r++
      ws.mergeCells(`B${r}:C${r}`)
      const a = ws.getCell(`B${r}`)
      a.value = label
      cellStyle(a, {})
      ws.getCell(`C${r}`).border = box
      const b = ws.getCell(`D${r}`)
      b.value = v
      cellStyle(b, { fmt: MONEY })
    })
    r++
    ws.mergeCells(`B${r}:C${r}`)
    const tl = ws.getCell(`B${r}`)
    tl.value = "Total"
    cellStyle(tl, { bold: true, fill: C.total })
    ws.getCell(`C${r}`).border = box
    const tv = ws.getCell(`D${r}`)
    tv.value = F(`SUM(D${top}:D${r - 1})`, rows.reduce((a, [, v]) => a + (v.result || 0), 0))
    cellStyle(tv, { bold: true, fill: C.total, fmt: MONEY })
  }
  block("Additions", [
    ["Overtime pay (approved hours)", F(S("otPay"), t.otPay)],
    ["Leave encashment (field, unused monthly leave)", F(S("encash"), t.encash)],
    ["Holiday pay (worked a weekend / holiday)", F(S("holPay"), t.holidayPay)],
    ["Bonus", F(S("bonus"), t.bonus)],
  ])
  block("Deductions", [
    ["Absent (LWP)", F(S("lwp"), t.lwp)],
    ["Late", F(S("lateAmt"), t.late)],
    ["Half day", F(S("halfAmt"), t.half)],
    ["Penalty", F(S("penalty"), t.penalty)],
    ["Advance recovered", F(`${R("O")}+${S("advance")}`, t.advance)],
    ["AIT (tax at source)", F(`${R("N")}+${S("ait")}`, t.ait)],
  ])
  signatures(ws, r + 5, W, ["Prepared By", "Checked By", "Managing Director"])
  ws.views = [{ showGridLines: false }]
  printSetup(ws, W, r + 5, `${H}:${H}`)
}

